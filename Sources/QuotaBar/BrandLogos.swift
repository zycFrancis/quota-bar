        case .deepseek: deepseek
        case .grok: grok
        case .gemini: gemini
        case .devin: devin
        }
    }

    private static func makeImage(svg: String) -> NSImage {
        guard let data = svg.data(using: .utf8),
              let image = NSImage(data: data) else {
            return NSImage(size: NSSize(width: 24, height: 24))
        }
        return image
    }

